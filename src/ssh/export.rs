//! Export Bifrost hosts as an ssh config file.
//!
//! The export goes to its own file, `~/.ssh/bifrost_config` by default, and
//! never touches `~/.ssh/config`. To use the hosts, the user adds this line
//! near the top of their own `~/.ssh/config`:
//!
//! ```text
//! Include ~/.ssh/bifrost_config
//! ```
//!
//! What is exported: `HostName`, `User`, `Port`, `IdentityFile` (with
//! `IdentitiesOnly yes`), `ProxyJump`, `LocalForward`, `RemoteForward` (both
//! bound to `127.0.0.1`) and `ForwardAgent yes` when enabled. Notes, tags and
//! favorites stay in Bifrost. `ProxyCommand` and `LocalCommand` are never
//! written.
//!
//! # ProxyJump limitation (0.1.0)
//!
//! A jump host is written as `user@host:port` taken from the Bifrost store,
//! and a jump host that itself has a jump host is written as a comma-separated
//! chain, first hop first (at most [`MAX_JUMP_HOPS`](crate::domain::jump::MAX_JUMP_HOPS)
//! hops). The jump host's own
//! `IdentityFile` is not part of that: its key must be in `ssh-agent` or be one
//! of ssh's default keys.
//!
//! Every value is validated again before it is written, and values are quoted
//! and escaped for ssh_config, so nothing in a host can start a new directive.

use std::fmt;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

use crate::domain::jump::jump_chain;
use crate::domain::validate::{self, Field, ValidationError};
use crate::domain::{Host, Hosts};
use crate::store::fsutil;
use crate::sysenv::{self, Env, Platform};
use crate::text::escape_control;

/// The first line of every exported file. A file that does not start with it
/// is not overwritten.
pub const GENERATED_HEADER: &str = "# Generated by Bifrost";

/// File name of the default export inside `~/.ssh`.
pub const EXPORT_FILE_NAME: &str = "bifrost_config";

#[derive(Debug)]
pub enum ExportError {
    NoHome,
    /// A host does not satisfy the validation rules (including jump chains).
    Invalid(ValidationError),
    /// A value contains characters that cannot be written to the file safely.
    /// Validation should make this unreachable; it is checked again here
    /// because this is the last step before untrusted-looking text becomes
    /// ssh configuration.
    UnsafeValue {
        host: String,
        field: &'static str,
    },
    /// The target exists but was not generated by Bifrost.
    NotGenerated(PathBuf),
    /// The target is an ssh `config` file, which Bifrost never writes.
    ProtectedTarget(PathBuf),
    Io {
        action: &'static str,
        path: PathBuf,
        source: io::Error,
    },
}

impl fmt::Display for ExportError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            ExportError::NoHome => f.write_str(
                "Could not find your home directory, so ~/.ssh/bifrost_config cannot be located.",
            ),
            ExportError::Invalid(err) => write!(f, "Cannot export: {err}"),
            ExportError::UnsafeValue { host, field } => write!(
                f,
                "Cannot export host '{}': its {field} contains characters that cannot be \
                 written safely.",
                escape_control(host)
            ),
            ExportError::NotGenerated(path) => write!(
                f,
                "{} already exists and was not generated by Bifrost, so it was left alone. \
                 Choose another file or move it away.",
                path.display()
            ),
            ExportError::ProtectedTarget(path) => write!(
                f,
                "{} looks like an ssh config file. Bifrost never writes to those; export to a \
                 separate file such as ~/.ssh/{EXPORT_FILE_NAME}.",
                path.display()
            ),
            ExportError::Io {
                action,
                path,
                source,
            } => write!(f, "Could not {action} {}: {source}", path.display()),
        }
    }
}

impl std::error::Error for ExportError {}

/// `~/.ssh/bifrost_config` (`%USERPROFILE%\.ssh\bifrost_config` on Windows).
pub fn default_export_path(platform: Platform, env: Env<'_>) -> Result<PathBuf, ExportError> {
    sysenv::home_dir(platform, env)
        .map(|home| home.join(".ssh").join(EXPORT_FILE_NAME))
        .ok_or(ExportError::NoHome)
}

/// Renders the ssh config text for `hosts`.
pub fn render(hosts: &Hosts) -> Result<String, ExportError> {
    render_slice(hosts.as_slice())
}

/// Renders and writes the export to `target`, user-only, atomically.
///
/// Refuses to write over a file that Bifrost did not generate, or to anything
/// named `config`. Missing parent directories are created user-only.
pub fn export_to(hosts: &Hosts, target: &Path) -> Result<(), ExportError> {
    let content = render(hosts)?;

    let is_ssh_config = target
        .file_name()
        .is_some_and(|name| name.to_string_lossy().eq_ignore_ascii_case("config"));
    if is_ssh_config {
        return Err(ExportError::ProtectedTarget(target.to_path_buf()));
    }

    match fs::read(target) {
        Ok(existing) if !existing.starts_with(GENERATED_HEADER.as_bytes()) => {
            return Err(ExportError::NotGenerated(target.to_path_buf()));
        }
        Ok(_) => {}
        Err(err) if err.kind() == io::ErrorKind::NotFound => {}
        Err(source) => {
            return Err(ExportError::Io {
                action: "read",
                path: target.to_path_buf(),
                source,
            });
        }
    }

    if let Some(parent) = target.parent().filter(|p| !p.as_os_str().is_empty()) {
        fsutil::ensure_private_dir(parent).map_err(|source| ExportError::Io {
            action: "create the directory",
            path: parent.to_path_buf(),
            source,
        })?;
    }
    fsutil::atomic_write(target, content.as_bytes()).map_err(|source| ExportError::Io {
        action: "write",
        path: target.to_path_buf(),
        source,
    })
}

fn render_slice(hosts: &[Host]) -> Result<String, ExportError> {
    // Same rules as when hosts are added, so a value that could never have
    // been saved can never be written either. This also guarantees that no
    // value holds a control character and that every jump chain resolves.
    validate::check_hosts(hosts).map_err(ExportError::Invalid)?;

    let mut out = String::new();
    out.push_str(GENERATED_HEADER);
    out.push_str(". Do not edit: changes are lost on the next export.\n");
    out.push_str("# To use these hosts, add this line near the top of ~/.ssh/config:\n");
    out.push_str(&format!("#   Include ~/.ssh/{EXPORT_FILE_NAME}\n"));
    for (index, host) in hosts.iter().enumerate() {
        let chain = jump_chain(hosts, host).map_err(|err| {
            ExportError::Invalid(
                ValidationError::new(Field::ProxyJump, err.to_string())
                    .with_host(index, &host.name),
            )
        })?;
        out.push('\n');
        render_host(&mut out, host, &chain)?;
    }
    Ok(out)
}

/// Appends one `Host` block. `chain` is the host's jump chain, first hop first.
///
/// Every value goes through [`arg`] or [`quote`], which refuse values that
/// could break out of their directive.
fn render_host(out: &mut String, host: &Host, chain: &[&Host]) -> Result<(), ExportError> {
    let unsafe_value = |field: &'static str| ExportError::UnsafeValue {
        host: host.name.clone(),
        field,
    };
    let word = |field: &'static str, value: &str| arg(value).map_err(|_| unsafe_value(field));

    out.push_str(&format!("Host {}\n", word("name", &host.name)?));
    out.push_str(&format!(
        "    HostName {}\n",
        word("hostname", &host.hostname)?
    ));
    if let Some(user) = &host.user {
        out.push_str(&format!("    User {}\n", word("user", user)?));
    }
    if let Some(port) = host.port {
        out.push_str(&format!("    Port {port}\n"));
    }
    if let Some(identity_file) = &host.identity_file {
        let quoted = quote(identity_file).map_err(|_| unsafe_value("identity file"))?;
        out.push_str(&format!("    IdentityFile {quoted}\n"));
        out.push_str("    IdentitiesOnly yes\n");
    }
    if !chain.is_empty() {
        let hops: Vec<String> = chain.iter().map(|hop| jump_spec(hop)).collect();
        out.push_str(&format!(
            "    ProxyJump {}\n",
            word("jump host", &hops.join(","))?
        ));
    }
    for (keyword, field, forwards) in [
        ("LocalForward", "local forward", &host.local_forwards),
        ("RemoteForward", "remote forward", &host.remote_forwards),
    ] {
        for forward in forwards {
            out.push_str(&format!(
                "    {keyword} {} {}\n",
                word(field, &endpoint("127.0.0.1", forward.listen_port))?,
                word(field, &endpoint(&forward.dest_host, forward.dest_port))?
            ));
        }
    }
    if host.forward_agent {
        out.push_str("    ForwardAgent yes\n");
    }
    Ok(())
}

/// `[user@]host:port` for one hop of a ProxyJump, with the port always explicit.
pub(super) fn jump_spec(hop: &Host) -> String {
    let endpoint = endpoint(&hop.hostname, hop.port.unwrap_or(22));
    match &hop.user {
        Some(user) => format!("{user}@{endpoint}"),
        None => endpoint,
    }
}

/// `host:port`, with brackets around IPv6 addresses.
pub(super) fn endpoint(host: &str, port: u16) -> String {
    if host.contains(':') {
        format!("[{host}]:{port}")
    } else {
        format!("{host}:{port}")
    }
}

/// A value that holds a control character or line break, which could end the
/// directive it is written into and start a new one.
#[derive(Debug, PartialEq, Eq)]
struct ControlCharacter;

/// A value as one ssh_config argument: bare when it only has safe characters,
/// otherwise quoted. Fails for control characters and line breaks, in release
/// builds too.
fn arg(value: &str) -> Result<String, ControlCharacter> {
    let bare = !value.is_empty()
        && value
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || "._-@:/~+,[]".contains(c));
    if bare {
        Ok(value.to_string())
    } else {
        quote(value)
    }
}

/// Always-quoted form. Backslash and double quote are escaped for ssh's
/// argument splitting, and `%` is doubled because ssh expands `%` tokens in
/// paths and jump specs. Fails for control characters and line breaks, in
/// release builds too: validated values never have them, but this check must
/// not depend on that.
fn quote(value: &str) -> Result<String, ControlCharacter> {
    if value.chars().any(char::is_control) {
        return Err(ControlCharacter);
    }
    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');
    for c in value.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '%' => out.push_str("%%"),
            c => out.push(c),
        }
    }
    out.push('"');
    Ok(out)
}

