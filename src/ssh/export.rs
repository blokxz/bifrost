    #[test]
    fn export_writes_the_file_and_creates_the_directory() {
        let dir = tempfile::tempdir().unwrap();
        let target = dir.path().join(".ssh").join("bifrost_config");
        export_to(&sample(), &target).unwrap();
        assert_eq!(
            fs::read_to_string(&target).unwrap(),
            render(&sample()).unwrap()
        );
        let leftovers: Vec<_> = fs::read_dir(target.parent().unwrap())
            .unwrap()
            .map(|e| e.unwrap().file_name())
            .collect();
        assert_eq!(leftovers.len(), 1, "{leftovers:?}");
    }

    #[test]
    fn export_replaces_a_previous_export() {
        let dir = tempfile::tempdir().unwrap();
        let target = dir.path().join("bifrost_config");
        export_to(&sample(), &target).unwrap();
        let mut updated = sample();
        updated.add(host("db", "db.example.com")).unwrap();
        export_to(&updated, &target).unwrap();
        let text = fs::read_to_string(&target).unwrap();
        assert!(text.contains("Host db\n") && text.contains("Host web\n"));
    }

    #[test]
    fn export_refuses_to_overwrite_files_it_did_not_generate() {
        let dir = tempfile::tempdir().unwrap();
        let target = dir.path().join("bifrost_config");
        fs::write(&target, "Host precious\n    HostName keep.example.com\n").unwrap();
        let err = export_to(&sample(), &target).unwrap_err();
        assert!(matches!(err, ExportError::NotGenerated(_)), "{err:?}");
        assert_eq!(
            fs::read_to_string(&target).unwrap(),
            "Host precious\n    HostName keep.example.com\n"
        );
    }

    #[test]
    fn export_never_writes_to_an_ssh_config_file() {
        let dir = tempfile::tempdir().unwrap();
        let config = dir.path().join("config");
        fs::write(&config, "Host mine\n").unwrap();
        for name in ["config", "CONFIG"] {
            let err = export_to(&sample(), &dir.path().join(name)).unwrap_err();
            assert!(
                matches!(err, ExportError::ProtectedTarget(_)),
                "{name}: {err:?}"
            );
        }
        assert_eq!(fs::read_to_string(&config).unwrap(), "Host mine\n");

        // Exporting next to it leaves it alone.
        export_to(&sample(), &dir.path().join("bifrost_config")).unwrap();
        assert_eq!(fs::read_to_string(&config).unwrap(), "Host mine\n");
    }

    #[test]
    fn a_failed_export_writes_nothing() {
        let dir = tempfile::tempdir().unwrap();
        let target = dir.path().join("bifrost_config");
        let mut hosts = sample();
        hosts.add(host("ok", "ok.example.com")).unwrap();
        // A directory in the way makes the final rename fail.
        fs::create_dir(&target).unwrap();
        assert!(export_to(&hosts, &target).is_err());
        assert!(target.is_dir());
    }

    #[cfg(unix)]
    #[test]
    fn exported_files_are_user_only() {
        use std::os::unix::fs::PermissionsExt;

        let dir = tempfile::tempdir().unwrap();
        let ssh_dir = dir.path().join(".ssh");
        let target = ssh_dir.join("bifrost_config");
        export_to(&sample(), &target).unwrap();
        let mode = |p: &Path| fs::metadata(p).unwrap().permissions().mode() & 0o777;
        assert_eq!(mode(&target), 0o600);
        assert_eq!(mode(&ssh_dir), 0o700);

        // Replacing a broader file makes it user-only again.
        fs::set_permissions(&target, fs::Permissions::from_mode(0o644)).unwrap();
        export_to(&sample(), &target).unwrap();
        assert_eq!(mode(&target), 0o600);
    }
