    #[test]
    fn arg_and_quote_refuse_control_characters_themselves() {
        // Called directly, bypassing validation: this is the last line of
        // defense, and it must hold in release builds too.
        for malicious in [
            "a\nProxyCommand id",
            "a\r\nProxyCommand id",
            "key\"\nProxyCommand id",
            "tab\there",
            "nul\0byte",
            "esc\x1b[31m",
            "del\x7f",
            "nel\u{85}",
            "\n",
        ] {
            assert_eq!(arg(malicious), Err(ControlCharacter), "arg {malicious:?}");
            assert_eq!(
                quote(malicious),
                Err(ControlCharacter),
                "quote {malicious:?}"
            );
        }
        // Printable non-ASCII text is not a control character.
        assert_eq!(quote("clé").unwrap(), "\"clé\"");
    }

    #[test]
    fn render_host_refuses_unsafe_values_even_without_validation() {
        // Bypass `check_hosts` and call the renderer directly, the way a bug
        // elsewhere could.
        let cases: Vec<(&str, Mutation)> = vec![
            ("name", Box::new(|h| h.name = "a\nProxyCommand id".into())),
            (
                "hostname",
                Box::new(|h| h.hostname = "h\nProxyCommand id".into()),
            ),
            (
                "user",
                Box::new(|h| h.user = Some("u\rProxyCommand id".into())),
            ),
            (
                "identity file",
                Box::new(|h| h.identity_file = Some("k\nProxyCommand id".into())),
            ),
            (
                "local forward",
                Box::new(|h| h.local_forwards.push(forward(1, "d\nProxyCommand id", 2))),
            ),
            (
                "remote forward",
                Box::new(|h| h.remote_forwards.push(forward(1, "d\x1b[31m", 2))),
            ),
        ];
        for (field, mutate) in cases {
            let mut evil = host("evil", "evil.example.com");
            mutate(&mut evil);
            let mut out = String::new();
            match render_host(&mut out, &evil, &[]) {
                Err(ExportError::UnsafeValue { field: got, .. }) => assert_eq!(got, field),
                other => panic!("{field}: unexpected result {other:?}"),
            }
        }

        // An unsafe value in a jump host is caught when its hop is written.
        let mut jump = host("jump", "jump.example.com");
        jump.user = Some("u\nProxyCommand id".into());
        let web = host("web", "web.example.com");
        let mut out = String::new();
        assert!(matches!(
            render_host(&mut out, &web, &[&jump]),
            Err(ExportError::UnsafeValue {
                field: "jump host",
                ..
            })
        ));
    }

    #[test]
    fn unsafe_value_errors_name_the_host_with_control_characters_escaped() {
        let err = ExportError::UnsafeValue {
            host: "a\x1b[31mb".into(),
            field: "hostname",
        };
        let message = err.to_string();
        assert!(!message.contains('\x1b'), "{message}");
        assert!(message.contains("hostname"), "{message}");
        assert!(message.contains("cannot be written safely"), "{message}");
    }

