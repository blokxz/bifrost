    /// Splits a line the way OpenSSH's argument splitter does: whitespace
    /// separates tokens, double quotes group, backslash escapes `\`, `"` and `'`.
    /// Then undoes `%%`, the only token ssh would expand.
    fn ssh_tokens(line: &str) -> Vec<String> {
        let mut tokens = Vec::new();
        let mut current = String::new();
        let mut started = false;
        let mut in_quotes = false;
        let mut chars = line.chars().peekable();
        while let Some(c) = chars.next() {
            match c {
                '\\' if matches!(chars.peek(), Some('\\' | '"' | '\'')) => {
                    current.push(chars.next().unwrap());
                    started = true;
                }
                '"' => {
                    in_quotes = !in_quotes;
                    started = true;
                }
                c if c.is_whitespace() && !in_quotes => {
                    if started {
                        tokens.push(std::mem::take(&mut current));
                        started = false;
                    }
                }
                c => {
                    current.push(c);
                    started = true;
                }
            }
        }
        assert!(!in_quotes, "unbalanced quotes in {line:?}");
        if started {
            tokens.push(current);
        }
        tokens.into_iter().map(|t| t.replace("%%", "%")).collect()
    }

    const ALLOWED_KEYWORDS: [&str; 10] = [
        "Host",
        "HostName",
        "User",
        "Port",
        "IdentityFile",
        "IdentitiesOnly",
        "ProxyJump",
        "LocalForward",
        "RemoteForward",
        "ForwardAgent",
    ];

    /// Every directive line must use a keyword Bifrost writes on purpose.
    fn assert_only_expected_directives(output: &str) {
        for line in output.lines() {
            let trimmed = line.trim();
            if trimmed.is_empty() || trimmed.starts_with('#') {
                continue;
            }
            let keyword = ssh_tokens(trimmed).remove(0);
            assert!(
                ALLOWED_KEYWORDS.contains(&keyword.as_str()),
                "unexpected directive in {line:?}"
            );
        }
    }

